<?php

namespace App\Http\Controllers\Dealer;

use App\Http\Controllers\Controller;

use Illuminate\Http\Request;

use App\Models\Stock;
use App\Models\StockRequest;
use App\Models\Dealer;

class StockRequestController extends Controller
{
    /*
    |--------------------------------------------------------------------------
    | REQUEST PAGE
    |--------------------------------------------------------------------------
    */

    public function index()
    {
        /*
        |--------------------------------------------------------------------------
        | GET LOGGED IN USER
        |--------------------------------------------------------------------------
        */

        $user = auth()->user();

        /*
        |--------------------------------------------------------------------------
        | FIND DEALER
        |--------------------------------------------------------------------------
        */

        $dealer = Dealer::where(
            'user_id',
            $user->id
        )->first();

        /*
        |--------------------------------------------------------------------------
        | IF DEALER NOT FOUND
        |--------------------------------------------------------------------------
        */

        if (!$dealer) {

            abort(404, 'Dealer not found');

        }

        /*
        |--------------------------------------------------------------------------
        | GET STOCKS
        |--------------------------------------------------------------------------
        */

        $stocks = Stock::latest()->get();

        /*
        |--------------------------------------------------------------------------
        | GET REQUESTS
        |--------------------------------------------------------------------------
        */

        $requests = StockRequest::with([

            'stock'

        ])

            ->where(
                'dealer_id',
                $dealer->id
            )

            ->latest()

            ->get();

        /*
        |--------------------------------------------------------------------------
        | RETURN VIEW
        |--------------------------------------------------------------------------
        */

        return view(
            'dealer.requests.index',
            compact(
                'stocks',
                'requests'
            )
        );
    }

    /*
    |--------------------------------------------------------------------------
    | STORE REQUEST
    |--------------------------------------------------------------------------
    */

    public function store(Request $request)
    {
        /*
        |--------------------------------------------------------------------------
        | VALIDATION
        |--------------------------------------------------------------------------
        */

        $request->validate([

            'stock_id' => 'required',

            'quantity' => 'required|numeric|min:1',

        ]);

        /*
        |--------------------------------------------------------------------------
        | GET LOGGED IN USER
        |--------------------------------------------------------------------------
        */

        $user = auth()->user();

        /*
        |--------------------------------------------------------------------------
        | FIND DEALER
        |--------------------------------------------------------------------------
        */

        $dealer = Dealer::where(
            'user_id',
            $user->id
        )->first();

        /*
        |--------------------------------------------------------------------------
        | IF DEALER NOT FOUND
        |--------------------------------------------------------------------------
        */

        if (!$dealer) {

            abort(404, 'Dealer not found');

        }

        /*
        |--------------------------------------------------------------------------
        | CREATE REQUEST
        |--------------------------------------------------------------------------
        */

        StockRequest::create([

            'dealer_id' =>

                $dealer->id,

            'stock_id' =>

                $request->stock_id,

            'quantity' =>

                $request->quantity,

            'notes' =>

                $request->notes,

            'status' =>

                'pending',

        ]);

        /*
        |--------------------------------------------------------------------------
        | REDIRECT
        |--------------------------------------------------------------------------
        */

        return redirect()
            ->route('dealer.requests.index')
            ->with(
                'success',
                'Request Sent Successfully'
            );
    }
}